-- Ejecutar como EXTREMETECH_PROD después de instalar las tablas base
-- y los triggers de venta, y de crear el usuario de base de datos USR_FINAL.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_tablas NUMBER;
BEGIN
    IF USER <> 'EXTREMETECH_PROD' THEN
        RAISE_APPLICATION_ERROR(-20991, 'Ejecute este script como EXTREMETECH_PROD.');
    END IF;

    SELECT COUNT(*) INTO v_tablas
    FROM USER_TABLES
    WHERE TABLE_NAME = 'EXT_USUARIOS_TB';

    IF v_tablas = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE EXT_USUARIOS_TB (
                IDUSUARIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                CORREO VARCHAR2(150) NOT NULL,
                PASSWORD_HASH VARCHAR2(255) NOT NULL,
                IDROL NUMBER NOT NULL,
                IDEMPLEADO NUMBER,
                IDCLIENTE NUMBER,
                ESTADO VARCHAR2(20) DEFAULT 'Activo' NOT NULL,
                FECHA_CREACION DATE DEFAULT SYSDATE,
                CONSTRAINT PK_EXT_USUARIOS PRIMARY KEY (IDUSUARIO),
                CONSTRAINT UQ_EXT_USUARIOS_CORREO UNIQUE (CORREO),
                CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('Activo', 'Inactivo')),
                CONSTRAINT CK_USUARIO_PERSONA CHECK (
                    (IDEMPLEADO IS NOT NULL AND IDCLIENTE IS NULL)
                    OR
                    (IDEMPLEADO IS NULL AND IDCLIENTE IS NOT NULL)
                ),
                CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (IDROL)
                    REFERENCES EXT_ROL_TB (IDROL),
                CONSTRAINT FK_USUARIO_EMPLEADO FOREIGN KEY (IDEMPLEADO)
                    REFERENCES EXT_EMPLEADOS_TB (IDEMPLEADO),
                CONSTRAINT FK_USUARIO_CLIENTE FOREIGN KEY (IDCLIENTE)
                    REFERENCES EXT_CLIENTES_TB (IDCLIENTE)
            )
        ]';
    END IF;
END;
/

CREATE OR REPLACE PROCEDURE SP_BUSCAR_USUARIO_LOGIN (
    p_correo  IN  VARCHAR2,
    p_usuario OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN p_usuario FOR
        SELECT IDUSUARIO, CORREO, PASSWORD_HASH,
               IDROL, IDEMPLEADO, IDCLIENTE, ESTADO
        FROM EXT_USUARIOS_TB
        WHERE LOWER(CORREO) = LOWER(TRIM(p_correo));
END;
/

CREATE OR REPLACE PROCEDURE SP_REVERTIR_VENTA_INCOMPLETA (
    p_idventa IN EXT_VENTAS_TB.IDVENTA%TYPE
)
AS
BEGIN
    SAVEPOINT antes_de_revertir_venta;

    DELETE FROM EXT_DETALLEVENTA_TB
    WHERE IDVENTA = p_idventa;

    DELETE FROM EXT_VENTAS_TB
    WHERE IDVENTA = p_idventa;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20211, 'La venta indicada no existe');
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO antes_de_revertir_venta;
        RAISE;
END;
/

SHOW ERRORS PROCEDURE SP_BUSCAR_USUARIO_LOGIN
SHOW ERRORS PROCEDURE SP_REVERTIR_VENTA_INCOMPLETA

DECLARE
    v_procedimientos NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_procedimientos
    FROM USER_OBJECTS
    WHERE OBJECT_TYPE = 'PROCEDURE'
      AND STATUS = 'VALID'
      AND OBJECT_NAME IN ('SP_BUSCAR_USUARIO_LOGIN', 'SP_REVERTIR_VENTA_INCOMPLETA');

    IF v_procedimientos <> 2 THEN
        RAISE_APPLICATION_ERROR(-20992, 'Revise los errores de compilación.');
    END IF;
END;
/

GRANT EXECUTE ON SP_BUSCAR_USUARIO_LOGIN TO USR_FINAL;
GRANT EXECUTE ON SP_REVERTIR_VENTA_INCOMPLETA TO USR_FINAL;
